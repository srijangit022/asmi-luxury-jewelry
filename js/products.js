/**
 * Intelligent SEO Metadata Generator for any Product
 * Crafts high-converting, Google SERP optimized metadata based on gemstones, metals & hallmarks
 */
function generateDefaultProductSEO(p) {
  if (!p) return {};
  const name = p.name || "Handcrafted Luxury Jewelry Piece";
  const metal = p.metal ? p.metal.split(" ")[0] : "22K Gold";
  const slug = (p.id || name.toLowerCase().replace(/[^a-z0-9]+/g, "-")).replace(/^[0-9]+-?/, "");
  const canonical = `https://asmijewelry.com/product/${slug}`;
  const gemShort = p.gemstone ? p.gemstone.split("(")[0].trim() : "Certified Gemstones";

  return {
    seoTitle: `${name} | BIS Hallmarked ${metal} | ASMI`,
    seoDescription: `Shop ${name} at ASMI. Handcrafted with ${gemShort}, authentic hallmark, and insured express delivery across India & worldwide.`,
    seoKeywords: `${name.toLowerCase()}, ${p.category || 'luxury jewelry'}, ${gemShort.toLowerCase()}, bis hallmarked jewelry, asmi luxury collection`,
    seoFocusKeyword: `${name.toLowerCase()}`,
    seoCanonicalUrl: canonical,
    seoRobots: "index, follow",
    seoOgTitle: `${name} | ASMI Haute Joaillerie`,
    seoOgDescription: (p.shortDesc || p.subtitle || `Exquisite handcrafted ${name} in luxury ${metal} finish.`).slice(0, 160),
    seoOgImage: p.image || "assets/images/hero-pearl-model.jpg",
    seoTwitterCard: "summary_large_image",
    seoSchemaType: "Product"
  };
}
window.generateDefaultProductSEO = generateDefaultProductSEO;

/**
 * Normalize and Ensure every product in an array has full SEO attributes
 */
function ensureProductsSEO(productsList) {
  if (!Array.isArray(productsList)) return [];
  return productsList.map(p => {
    const fallback = generateDefaultProductSEO(p);
    const resolvedImg = resolveAssetUrl(p.image || fallback.seoOgImage);
    const resolvedAlt = Array.isArray(p.altImages) && p.altImages.length > 0
      ? p.altImages.map(img => resolveAssetUrl(img))
      : [resolvedImg];
    return {
      ...fallback,
      ...p,
      image: resolvedImg,
      altImages: resolvedAlt,
      seoTitle: p.seoTitle || fallback.seoTitle,
      seoDescription: p.seoDescription || fallback.seoDescription,
      seoKeywords: p.seoKeywords || fallback.seoKeywords,
      seoFocusKeyword: p.seoFocusKeyword || fallback.seoFocusKeyword,
      seoCanonicalUrl: p.seoCanonicalUrl || fallback.seoCanonicalUrl,
      seoRobots: p.seoRobots || fallback.seoRobots || "index, follow",
      seoOgTitle: p.seoOgTitle || fallback.seoOgTitle,
      seoOgDescription: p.seoOgDescription || fallback.seoOgDescription,
      seoOgImage: resolveAssetUrl(p.seoOgImage || p.image || fallback.seoOgImage),
      seoTwitterCard: p.seoTwitterCard || "summary_large_image",
      seoSchemaType: p.seoSchemaType || "Product"
    };
  });
}
window.ensureProductsSEO = ensureProductsSEO;

/**
 * Dynamic Asset URL Resolver
 * Automatically resolves relative asset paths to WordPress theme directory if in WP environment
 */
function resolveAssetUrl(path) {
  if (!path) return "";
  if (path.startsWith("http://") || path.startsWith("https://") || path.startsWith("data:")) {
    return path;
  }
  let themeBase = "";
  if (typeof asmi_wp_data !== "undefined" && asmi_wp_data.themeUrl) {
    themeBase = asmi_wp_data.themeUrl.replace(/\/+$/, "") + "/";
  } else if (window.ASMI_THEME_URI) {
    themeBase = window.ASMI_THEME_URI.replace(/\/+$/, "") + "/";
  } else {
    const meta = document.querySelector('meta[name="asmi-theme-uri"]');
    if (meta && meta.getAttribute("content")) {
      themeBase = meta.getAttribute("content").replace(/\/+$/, "") + "/";
    } else {
      themeBase = "";
    }
  }
  return themeBase + path.replace(/^\/+/, "");
}
window.resolveAssetUrl = resolveAssetUrl;

function loadProductsFromStorage() {
  if (typeof asmi_wp_data !== "undefined" && asmi_wp_data.preloaded && Array.isArray(asmi_wp_data.preloaded.products)) {
    return ensureProductsSEO(asmi_wp_data.preloaded.products);
  }
  try {
    const saved = localStorage.getItem("asmi_products_data");
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed)) return ensureProductsSEO(parsed);
    }
  } catch (e) {
    console.warn("Could not load products from localStorage", e);
  }

  // Synchronous XHR fallback to data/products.json with cache-busting for instant first-load hydration
  try {
    if (typeof XMLHttpRequest !== "undefined") {
      const xhr = new XMLHttpRequest();
      const rawUrl = (typeof resolveAssetUrl === "function" ? resolveAssetUrl("data/products.json") : "data/products.json");
      const productsUrl = rawUrl + (rawUrl.includes("?") ? "&" : "?") + "_t=" + Date.now();
      xhr.open("GET", productsUrl, false);
      xhr.send(null);
      if (xhr.status === 200 || xhr.status === 0) {
        const parsed = JSON.parse(xhr.responseText);
        if (Array.isArray(parsed)) {
          try { localStorage.setItem("asmi_products_data", JSON.stringify(parsed)); } catch (err) {}
          return ensureProductsSEO(parsed);
        }
      }
    }
  } catch (xhrErr) {
    console.warn("Synchronous product hydration fallback failed, using defaults:", xhrErr);
  }

  return ensureProductsSEO([...INITIAL_PRODUCTS_DATA]);
}

let PRODUCTS_DATA = loadProductsFromStorage();
window.PRODUCTS_DATA = PRODUCTS_DATA;

// Multi-Currency Definition (INR ₹ & USD $)
const CURRENCY_RATES = {
  INR: { symbol: "₹", rate: 1, name: "INR (₹)", prefix: "₹", code: "INR" },
  USD: { symbol: "$", rate: 0.012, name: "USD ($)", prefix: "$", code: "USD" }
};

let currentCurrency = localStorage.getItem("asmi_currency") || "INR";

/**
 * Universal Multi-Currency Price Formatter
 * Formats price into INR (₹) or USD ($) dynamically based on selected active currency
 */
function formatPrice(inrAmount, currencyCode = null, usdAmount = null) {
  const activeCurrency = currencyCode || currentCurrency || localStorage.getItem("asmi_currency") || "INR";
  const numINR = Number(inrAmount) || 0;

  if (activeCurrency === "USD") {
    if (usdAmount !== null && usdAmount !== undefined && Number(usdAmount) > 0) {
      return `$${Math.round(Number(usdAmount)).toLocaleString("en-US")}`;
    }
    const valUSD = Math.round(numINR * CURRENCY_RATES.USD.rate);
    return `$${valUSD.toLocaleString("en-US")}`;
  }

  const valINR = Math.round(numINR);
  return `₹${valINR.toLocaleString("en-IN")}`;
}

function setCurrency(currencyCode) {
  if (CURRENCY_RATES[currencyCode]) {
    currentCurrency = currencyCode;
    localStorage.setItem("asmi_currency", currencyCode);

    document.querySelectorAll(".currency-select-input, #currencySelector").forEach(el => {
      el.value = currencyCode;
    });

    if (typeof window.renderCatalog === "function") window.renderCatalog();
    else if (typeof renderCatalog === "function") renderCatalog();
    if (typeof renderProductCatalog === "function") renderProductCatalog();
    if (typeof updateCartUI === "function") updateCartUI();
    if (typeof cartManager !== "undefined" && cartManager && typeof cartManager.renderCartDrawer === "function") {
      cartManager.renderCartDrawer();
    }
    if (typeof adminManager !== "undefined" && adminManager && typeof adminManager.renderProductsTable === "function") {
      adminManager.renderProductsTable();
    }
    window.dispatchEvent(new CustomEvent("currencyChanged", { detail: { currency: currencyCode } }));
  }
}

function toggleCurrency() {
  const next = (currentCurrency === "INR") ? "USD" : "INR";
  setCurrency(next);
}

window.formatPrice = formatPrice;
